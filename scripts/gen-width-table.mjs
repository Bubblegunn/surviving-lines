#!/usr/bin/env node
/**
 * Regenerate the East Asian Width table in bin/surviving-lines.js from the Unicode Character
 * Database, so the widths the table pads to are the standard's rather than a hand-written guess.
 *
 *   node scripts/gen-width-table.mjs          # rewrite the table in place
 *   node scripts/gen-width-table.mjs --check  # exit non-zero if the file is out of date
 *
 * Needs network access, which is why it is a manual script and not a test: CI runs offline.
 * The generated block sits between the WIDE-TABLE markers and is the Wide and Fullwidth classes
 * of UAX #11 (https://www.unicode.org/reports/tr11/), merged into ranges.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const SRC = "https://www.unicode.org/Public/UCD/latest/ucd/EastAsianWidth.txt";
const target = join(dirname(fileURLToPath(import.meta.url)), "..", "bin", "surviving-lines.js");
const check = process.argv.includes("--check");

const body = await (await fetch(SRC)).text();
const version = /EastAsianWidth-([\d.]+)\.txt/.exec(body)?.[1];
if (!version) throw new Error(`no version header in ${SRC}`);

/** @type {[number, number][]} */
const ranges = [];
for (const line of body.split("\n")) {
  const row = line.split("#")[0].trim();
  if (!row) continue;
  const [range, prop] = row.split(";").map((s) => s.trim());
  if (prop !== "W" && prop !== "F") continue;
  const [lo, hi] = range.split("..");
  ranges.push([Number.parseInt(lo, 16), Number.parseInt(hi ?? lo, 16)]);
}
ranges.sort((a, b) => a[0] - b[0]);
/** @type {[number, number][]} */
const merged = [];
for (const [lo, hi] of ranges) {
  const last = merged.at(-1);
  if (last && lo <= last[1] + 1) last[1] = Math.max(last[1], hi);
  else merged.push([lo, hi]);
}

const hex = (/** @type {number} */ n) => `0x${n.toString(16)}`;
const flat = merged.flat().map(hex);
/** @type {string[]} */
const wrapped = [];
for (let i = 0; i < flat.length; i += 10) wrapped.push(`  ${flat.slice(i, i + 10).join(", ")},`);
const block = [
  `// WIDE-TABLE start — generated by scripts/gen-width-table.mjs from Unicode ${version}. Do not edit by hand.`,
  `/** Inclusive [start, end] pairs of the Wide and Fullwidth classes of UAX #11, ${merged.length} ranges. */`,
  "const WIDE = [",
  ...wrapped,
  "];",
  "// WIDE-TABLE end",
].join("\n");

const before = readFileSync(target, "utf8");
const after = before.replace(/\/\/ WIDE-TABLE start[\s\S]*?\/\/ WIDE-TABLE end/, () => block);
if (after === before) {
  console.log(`already current: Unicode ${version}, ${merged.length} ranges`);
  process.exit(0);
}
if (!/\/\/ WIDE-TABLE start/.test(before)) throw new Error("WIDE-TABLE markers not found in bin/surviving-lines.js");
if (check) {
  console.error(`out of date: bin/surviving-lines.js does not match Unicode ${version}. Run: node scripts/gen-width-table.mjs`);
  process.exit(1);
}
writeFileSync(target, after);
console.log(`wrote Unicode ${version}, ${merged.length} ranges, ${merged.reduce((s, [a, b]) => s + b - a + 1, 0)} code points`);
