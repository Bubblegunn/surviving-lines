#!/usr/bin/env bash
# Usage: build-fixture.sh <dest-dir>
# Clones the upstream repo, pins one commit, drops the remote, then adds
# synthetic commits with fixed authors/dates so every build has the same shas.
set -euo pipefail
URL=https://github.com/fatih/color
PIN=820c6ebc21b06a3a5328297d556a87f91556e577
DEST="${1:?usage: build-fixture.sh <dest-dir>}"
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null GIT_TERMINAL_PROMPT=0
rm -rf "$DEST"
git clone -q "$URL" "$DEST"
cd "$DEST"
git checkout -q -B master "$PIN"
git remote remove origin
for r in $(git for-each-ref --format='%(refname)' refs/heads refs/tags refs/remotes | grep -v '^refs/heads/master$' || true); do git update-ref -d "$r"; done
git config core.autocrlf false
git config commit.gpgsign false
[ "$(git rev-parse HEAD)" = "$PIN" ] || { echo "pin mismatch" >&2; exit 1; }

# cm "Author Name" "author@mail" "date" "message" ["Committer Name" "committer@mail"]
cm() {
  local an="$1" ae="$2" d="$3" msg="$4" cn="${5:-$1}" ce="${6:-$2}"
  git add -A
  GIT_AUTHOR_NAME="$an" GIT_AUTHOR_EMAIL="$ae" GIT_AUTHOR_DATE="$d" \
  GIT_COMMITTER_NAME="$cn" GIT_COMMITTER_EMAIL="$ce" GIT_COMMITTER_DATE="$d" \
  git commit -q --no-verify -m "$msg"
}
# Run a git command that creates a commit (revert) as the given identity/date.
as() {
  local an="$1" ae="$2" d="$3"; shift 3
  GIT_AUTHOR_NAME="$an" GIT_AUTHOR_EMAIL="$ae" GIT_AUTHOR_DATE="$d" \
  GIT_COMMITTER_NAME="$an" GIT_COMMITTER_EMAIL="$ae" GIT_COMMITTER_DATE="$d" "$@"
}

RAJ=("Raj Patel" "<email redacted>")
LENA=("Lena Hoffmann" "<email redacted>")

# Raj: vendored third-party dependency (go mod vendor)
mkdir -p vendor/github.com/mattn/go-isatty
python3 - <<'PY'
hdr = "//go:build !windows && !plan9\n\npackage isatty\n\nimport \"syscall\"\n\n"
body = hdr + "// IsTerminal returns true if the file descriptor is a terminal.\nfunc IsTerminal(fd uintptr) bool {\n\tvar termios syscall.Termios\n\t_, _, err := syscall.Syscall6(syscall.SYS_IOCTL, fd, ioctlReadTermios, uintptr(unsafe.Pointer(&termios)), 0, 0, 0)\n\treturn err == 0\n}\n\n"
out = body
for i in range(1, 15):
    out += "// IsCygwinTerminal%d reports whether fd is a Cygwin/MSYS2 pty (variant %d).\nfunc IsCygwinTerminal%d(fd uintptr) bool {\n\tif fd == 0 {\n\t\treturn false\n\t}\n\treturn %d > 0\n}\n\n" % (i, i, i, i)
open("vendor/github.com/mattn/go-isatty/isatty_tcgets.go", "w").write(out)
open("vendor/modules.txt", "w").write("# github.com/mattn/go-isatty v0.0.20\n## explicit; go 1.15\ngithub.com/mattn/go-isatty\n")
PY
cm "${RAJ[@]}" "2026-08-03T09:00:00+0000" "build: vendor dependencies"

# Lena: stringer output for Attribute (generated file, committed)
python3 - <<'PY'
names = {}
for i, n in enumerate(["Reset", "Bold", "Faint", "Italic", "Underline", "BlinkSlow", "BlinkRapid", "ReverseVideo", "Concealed", "CrossedOut"]):
    names[i] = n
cols = ["Black", "Red", "Green", "Yellow", "Blue", "Magenta", "Cyan", "White"]
for prefix, base in (("Fg", 30), ("Bg", 40), ("FgHi", 90), ("BgHi", 100)):
    for j, c in enumerate(cols):
        names[base + j] = prefix + c
lines = ['// Code generated by "stringer -type=Attribute -output=attribute_string.go"; DO NOT EDIT.', "", "package color", "", "import \"strconv\"", "",
         "func _() {", "\t// An \"invalid array index\" compiler error signifies that the constant values have changed.", "\t// Re-run the stringer command to generate them again.", "\tvar x [1]struct{}", "\t_ = x[Reset-0]", "}", "",
         "func (i Attribute) String() string {", "\tswitch i {"]
for v, n in sorted(names.items()):
    lines += ["\tcase %s:" % n, "\t\treturn \"%s\"" % n]
lines += ["\tdefault:", "\t\treturn \"Attribute(\" + strconv.FormatInt(int64(i), 10) + \")\"", "\t}", "}", ""]
open("attribute_string.go", "w").write("\n".join(lines))
PY
cm "${LENA[@]}" "2026-08-10T13:30:00+0000" "Add generated String method for Attribute"

# Raj: gofmt -r 'interface{} -> any' over all non-vendored Go files; sha recorded in .git-blame-ignore-revs
python3 - <<'PY'
import subprocess
n = 0
for p in subprocess.check_output(["git", "ls-files", "*.go"], text=True).split():
    if p.startswith("vendor/"):
        continue
    s = open(p).read()
    t = s.replace("interface{}", "any")
    n += s.count("interface{}")
    open(p, "w").write(t)
print("replaced", n)
PY
cm "${RAJ[@]}" "2026-08-17T10:00:00+0000" "all: use any instead of interface{}"
printf "# gofmt -r 'interface{} -> any'\n%s\n" "$(git rev-parse HEAD)" > .git-blame-ignore-revs
cm "${RAJ[@]}" "2026-08-17T10:05:00+0000" "Add .git-blame-ignore-revs"

# Raj: move the Attribute type and constants out of color.go into attribute.go (pure move)
python3 - <<'PY'
L = open("color.go").read().split("\n")
a = L.index("// Attribute defines a single SGR Code")
b = L.index("// New returns a newly created color object.")
moved = L[a:b]
open("attribute.go", "w").write("package color\n\n" + "\n".join(moved).rstrip("\n") + "\n")
open("color.go", "w").write("\n".join(L[:a] + L[b:]))
print("moved lines:", len(moved))
PY
cm "${RAJ[@]}" "2026-08-24T15:00:00+0000" "refactor: move Attribute and its constants to attribute.go"

[ -z "$(git status --porcelain)" ] || { echo "dirty tree" >&2; exit 1; }
[ "$(git rev-parse --abbrev-ref HEAD)" = master ]
echo "built $(git rev-parse HEAD)"

