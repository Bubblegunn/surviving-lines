/// Prints "<name> <version>" followed by a newline.
pub fn printVersion(name: []const u8, version: std.SemanticVersion, writer: *std.Io.Writer) !void {
    try writer.print("{s} {d}.{d}.{d}", .{ name, version.major, version.minor, version.patch });
    if (version.pre) |pre| {
        try writer.print("-{s}", .{pre});
    }
    try writer.print("\n", .{});
}

test "printVersion" {
    var buf: [64]u8 = undefined;
    var w: std.Io.Writer = .fixed(&buf);
    try printVersion("demo", .{ .major = 1, .minor = 2, .patch = 3 }, &w);
    try std.testing.expectEqualStrings("demo 1.2.3\n", w.buffered());
}
ZIG
