cat > src/width.zig <<'ZIG'
const std = @import("std");
const table = @import("width_table.zig");

/// Number of terminal columns `codepoint` occupies (1 or 2).
pub fn codepointWidth(codepoint: u21) u2 {
    var lo: usize = 0;
    var hi: usize = table.wide_ranges.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        const range = table.wide_ranges[mid];
        if (codepoint < range[0]) {
            hi = mid;
        } else if (codepoint > range[1]) {
            lo = mid + 1;
        } else {
            return 2;
        }
    }
    return 1;
}

test "ascii is narrow" {
    try std.testing.expectEqual(@as(u2, 1), codepointWidth('a'));
}
ZIG
