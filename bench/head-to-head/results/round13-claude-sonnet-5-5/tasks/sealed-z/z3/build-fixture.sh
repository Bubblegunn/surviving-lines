# 6. Wen: width helper plus its generated table
python3 -I - <<'PY'
out = ['// Generated by tools/gen_width.zig from EastAsianWidth.txt. DO NOT EDIT.', '',
       'pub const wide_ranges = [_][2]u21{']
for i in range(480):
    lo = 0x1100 + i * 7
    out.append('    .{ 0x%04x, 0x%04x },' % (lo, lo + 3))
out += ['};', '']
