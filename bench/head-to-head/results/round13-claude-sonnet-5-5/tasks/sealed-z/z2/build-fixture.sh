package uuid

// NewV8 returns a Version 8 (custom) UUID built from 16 bytes of caller
// supplied data.  The version and variant bits of data are overwritten, the
// other 122 bits are kept as given.
//
// see https://datatracker.ietf.org/doc/html/rfc9562#name-uuid-version-8
func NewV8(data [16]byte) UUID {
	uuid := UUID(data)
	uuid[6] = (uuid[6] & 0x0f) | 0x80 // version 8
	uuid[8] = (uuid[8] & 0x3f) | 0x80 // variant 10
	return uuid
}

// V8Payload returns the 16 bytes of a Version 8 UUID with the version and
// variant bits cleared, the inverse of NewV8 up to those six bits.
func (uuid UUID) V8Payload() [16]byte {
	p := [16]byte(uuid)
	p[6] &= 0x0f
	p[8] &= 0x3f
	return p
}
GO
