package uuid

// Option configures optional behaviour of the package.
type Option func(*options)

type options struct {
	monotonic bool
	strict    bool
}

// WithMonotonic asks generators for values that never decrease within one
// process, even if the system clock steps backwards.
func WithMonotonic() Option {
	return func(o *options) { o.monotonic = true }
}

// WithStrict makes generators return an error instead of falling back to
// weaker sources of randomness.
func WithStrict() Option {
	return func(o *options) { o.strict = true }
}

func newOptions(opts []Option) options {
	var o options
	for _, f := range opts {
		f(&o)
	}
	return o
}
GO
