# Fixture for task t2: whole-repo ownership of expressjs/morgan pinned at
# b1272e70812dbc504321eeb5a43d14b0822c150d, plus synthetic pitfall commits.
set -euo pipefail
DEST="${1:?usage: build-fixture.sh <dest-dir>}"
