commit_as() { # name email date message
  GIT_AUTHOR_NAME="$1" GIT_AUTHOR_EMAIL="$2" GIT_AUTHOR_DATE="$3" \
  GIT_COMMITTER_NAME="$1" GIT_COMMITTER_EMAIL="$2" GIT_COMMITTER_DATE="$3" \
  git commit -q -m "$4"
}
gen_block() { # prefix count -> CommonJS-ish helper functions (standard style, no semicolons)
python3 -I - "$1" "$2" <<'PY'
import sys
p, n = sys.argv[1], int(sys.argv[2])
out = []
for i in range(n):
    out += [
        f"function {p}Format{i} (value, fallback) {{",
        f"  var text = value == null ? fallback : value",
        f"  if (typeof text === 'string') {{",
        f"    return text.trim() + '|{p}{i}'",
        f"  }}",
        f"  return String(text)",
        f"}}",
        f"",
    ]
print("\n".join(out))
PY
}

# 1. One maintainer under two identities, both landed through a merge commit
git checkout -q -b feature/formats
