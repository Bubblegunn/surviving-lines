test("copy detection: a block moved to a new file is credited to its first author; --no-copies credits the mover", async () => {
  await withRepo(
    (dir) => {
      commitAs(dir, "ada", D("01"), "write", { "src/a.js": LONG("moved", 30) + lines("rest", 10) });
      commitAs(dir, "bob", D("02"), "move", { "src/a.js": lines("rest", 10), "src/c.js": LONG("moved", 30) });
    },
    async (dir) => {
      const on = await run(dir);
      assert.deepEqual(on.blame.flags, ["-w", "-M", "-C"]);
      assert.equal(on.blame.copyDetection.on, true);
      assert.equal(on.authors.find((a) => a.mail === "ada@example.com")?.lines, 40);
      assert.equal(on.authors.find((a) => a.mail === "bob@example.com")?.lines, 0);
      const off = await run(dir, ["--no-copies"]);
      assert.deepEqual(off.blame.flags, ["-w", "-M"]);
      assert.equal(off.authors.find((a) => a.mail === "bob@example.com")?.lines, 30);
      const explicit = await run(dir, ["--copies"]);
      assert.deepEqual(explicit.blame.flags, ["-w", "-M", "-C"]);
      const deep = await run(dir, ["--copies", "deep"]);
      assert.deepEqual(deep.blame.flags, ["-w", "-M", "-C", "-C"]);
      assert.equal(deep.blame.copyDetection.flags, "-C -C");
      assert.throws(() => parseArgs(["--copies", "--no-copies"]), /mutually exclusive|--copies/);
    },
  );
});

test("moved in: reviewers and history say the lines were written elsewhere, from 5% up, and the JSON carries the field", async () => {
  await withRepo(
    (dir) => {
      commitAs(dir, "ada", D("01"), "write", { "old/a.js": LONG("moved", 30) + lines("rest", 10) });
      commitAs(dir, "bob", D("02"), "move", { "old/a.js": lines("rest", 10), "src/c.js": LONG("moved", 30) });
    },
    async (dir) => {
      const r = await run(dir, ["--reviewers", "src"]);
      assert.equal(r.reviewers?.movedIn?.lines, 30);
      assert.equal(r.reviewers?.movedIn?.of, 30);
      assert.deepEqual(r.reviewers?.movedIn?.largest, [{ path: "old/a.js", lines: 30 }]);
      const text = renderReviewers(r, 10);
      assert.match(text, /30 of 30 lines \(100\.0%\) in src were written in other paths and moved or copied here \(largest source: old\/a\.js\); the credit goes to the people who wrote them, not to whoever moved them\./);
      assert.equal(r.authors[0].mail, "ada@example.com");
      assert.deepEqual(schemaErrors(JSON.parse(renderJson(r))), []);
      const h = await run(dir, ["--history", "src"]);
      assert.match(renderHistory(h, 10), /written in other paths and moved or copied here/);
      assert.match(renderHistory(h, 10), /Bob made the first commit, on [0-9-]+; Ada holds the most lines now \(30 lines, 100\.0%\) and has no commit on this path/);
      assert.equal(h.history?.movedIn?.share, 1);
      const none = await run(dir, ["--reviewers", "old"]);
      assert.equal(none.reviewers?.movedIn?.lines, 0);
      assert.doesNotMatch(renderReviewers(none, 10), /written in other paths/);
    },
  );
});

test("countBlameOrigins counts the lines whose filename header differs from the blamed path", () => {
  const porcelain = ["filename a.js", "\tx", "filename b.js", "\ty", "filename b.js", "\tz"].join("\n");
  const c = countBlameOrigins(porcelain, "a.js");
  assert.equal(c.total, 3);
  assert.deepEqual([...c.from], [["b.js", 2]]);
});

test("above the file gate copy detection stays off and the output says why; --copies turns it on", async () => {
  await withRepo(
    (dir) => commitAs(dir, "ada", D("01"), "init", { "a.js": lines("a", 3), "b.js": lines("b", 3), "c.js": lines("c", 3) }),
    async (dir) => {
      // The gate is 2000 files; the message is checked through the renderer with a result shaped as the gate leaves it.
      const r = await run(dir);
      const gated = { ...r, blame: { ...r.blame, copyDetection: { on: false, reason: "2,500 files to blame, more than 2000" } } };
      assert.match(renderTable(gated, 10), /^copy detection off: 2,500 files to blame, more than 2000, so code moved or copied between files is credited to whoever moved it \(-w -M only\)\. --copies turns it on/m);
      assert.doesNotMatch(renderTable(r, 10), /copy detection off/);
    },
  );
});

test("the table and the JSON give the number of authors that reach 80% next to the bus factor", async () => {
  await withRepo(
    (dir) => {
      commitAs(dir, "ada", D("01"), "a", { "a.js": lines("a", 50) });
      commitAs(dir, "bob", D("02"), "b", { "b.js": lines("b", 25) });
      commitAs(dir, "charlie", D("03"), "c", { "c.js": lines("c", 25) });
    },
    async (dir) => {
      const r = await run(dir);
      assert.equal(r.busFactor?.value, 1);
      assert.equal(r.busFactor?.authorsFor80Percent, 3);
      assert.match(renderTable(r, 10), /^bus factor 1: Ada alone holds 50\.0% of 100 surviving lines · to reach 80%: 3 authors$/m);
      const wide = await run(dir, ["--bus-factor-threshold", "90"]);
      assert.equal(wide.busFactor?.authorsFor80Percent, 3);
      assert.deepEqual(schemaErrors(JSON.parse(renderJson(r))), []);
    },
  );
});

test("a quoted origin path (non-ASCII letters, a quote) is read back before it is compared with the blamed path", async () => {
  assert.equal(unquoteGitPath('"caf\\303\\251.ts"'), "café.ts");
  assert.equal(unquoteGitPath('"a\\"b.js"'), 'a"b.js');
  assert.equal(unquoteGitPath("plain.js"), "plain.js");
  await withRepo(
    (dir) => {
      commitAs(dir, "ada", D("01"), "write", { "src/café.ts": lines("own", 12) });
    },
    async (dir) => {
      const r = await run(dir, ["--reviewers", "src"]);
      assert.equal(r.reviewers?.movedIn?.lines, 0);
    },
  );
});

