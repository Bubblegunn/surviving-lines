test("possible same person: accent-folded names, a name contained in an address are suggested and never merged", async () => {
  await withRepo(
    (dir) => {
      commitAsIdentity(dir, ["Zoë Kaya", "zk1@a.example"], D("01"), "a", { "a.js": lines("a", 8) });
      commitAsIdentity(dir, ["Zoe Kaya", "zk2@b.example"], D("02"), "b", { "b.js": lines("b", 6) });
      commitAsIdentity(dir, ["Quinn Park", "12345+quinnp@users.noreply.github.com"], D("03"), "c", { "c.js": lines("c", 5) });
      commitAsIdentity(dir, ["Q Rivera", "quinnp@users.noreply.github.com"], D("04"), "d", { "d.js": lines("d", 4) });
      commitAsIdentity(dir, ["Maria Santos", "msantos@work.example"], D("05"), "e", { "e.js": lines("e", 3) });
      commitAsIdentity(dir, ["Maria S", "maria.santos2@home.example"], D("06"), "f", { "f.js": lines("f", 2) });
    },
    async (dir) => {
      for (const args of [[], ["--merge-identities"]]) {
        const r = await run(dir, args);
        const all = r.possibleSamePerson.suggestions.flatMap((s) => s.evidence);
        assert.ok(all.some((e) => /equal once accents are removed/.test(e)), all.join("\n"));
        assert.ok(all.some((e) => /contained in the address/.test(e)), all.join("\n"));
        assert.equal(r.possibleSamePerson.merged, false);
        assert.deepEqual(r.authors.filter((a) => /^zk/.test(a.mail)).map((a) => a.mail).sort(), ["zk1@a.example", "zk2@b.example"]);
        const accent = r.possibleSamePerson.suggestions.find((s) => s.evidence.some((e) => /accents/.test(e)));
        assert.deepEqual(accent?.mailmap.length, 1);
        assert.match(accent?.mailmap[0] ?? "", /^.+ <zk[12]@[ab]\.example> <zk[12]@[ab]\.example>$/);
      }
      const text = renderTable(await run(dir), 10);
      assert.match(text, /^possible same person: 2 suggestions, not merged/m);
    },
  );
});

