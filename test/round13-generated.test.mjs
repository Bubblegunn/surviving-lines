// @ts-check
// Round 13, G4: generated output is recognised by more header phrasings (any case, on a comment line) and by a compiled
// output that sits beside, or in a src directory over, its source. Fixtures are tiny repositories with invented names.
import { test } from "node:test";
import assert from "node:assert/strict";
import { commitAs, createRepo, lines, removeRepo } from "../scripts/fixtures.mjs";

const { parseArgs, analyse, droppedLine } = await import("../bin/surviving-lines.js");

/**
 * One commit by Ada with the files, analysed with the extra arguments.
 * @param {Record<string, string>} files
 * @param {string[]} [args]
 */
async function run(files, args = []) {
  const dir = createRepo("sl-gen-");
  try {
    commitAs(dir, "ada", "2026-01-01T10:00:00Z", "feat: add the files", { "keep.txt": lines("k", 5), ...files });
    return await analyse(parseArgs(["--cwd", dir, ...args]));
  } finally {
    removeRepo(dir);
  }
}
/** @param {any} r */
const droppedPaths = (r) => r.dropped.paths.map((/** @type {any} */ p) => p.path).sort();

test("the wide header phrasings drop a file, in any case, on a comment line", async () => {
  const heads = [
    "// This file was generated by the toy tool",
    "# GENERATED FILE - do not hand edit",
    "-- autogenerated from the schema",
    "/* Automatically generated. */",
    "; do not modify this file",
    "% do not change: produced by the exporter",
    "<!-- compiled from pages/index.md -->",
    "// auto-generated by gen",
    "# Generated Code",
  ];
  const files = Object.fromEntries(heads.map((h, i) => [`g/f${i}.txt`, `${h}\n${lines("x", 6)}`]));
  const r = await run(files);
  assert.equal(r.dropped.classes.generated.files, heads.length);
  assert.deepEqual(droppedPaths(r), Object.keys(files).sort());
});

test("a block comment that opens above the phrase marks the file", async () => {
  const r = await run({ "b/doc.txt": `/*\n  Header of the output\n  Produced by the exporter\n*/\n${lines("y", 6)}` });
  assert.deepEqual(droppedPaths(r), ["b/doc.txt"]);
});

test("a source file that only uses the word in code is kept", async () => {
  const r = await run({
    "src/a.js": `let generated = 1;\nconst produced = generated + 1;\n${lines("a", 6)}`,
    "src/b.js": `// the generated ids are stable\n${lines("b", 6)}`,
    "src/c.js": `const note = "do not edit the produced by line";\n${lines("c", 6)}`,
  });
  assert.equal(r.dropped.files, 0);
  assert.equal(droppedLine(r), null);
});

test("the original case-sensitive markers still drop a file wherever they stand in the first lines", async () => {
  const r = await run({ "o/a.go": `package a\nvar x = 1 // Code generated by foo. DO NOT EDIT.\n${lines("a", 6)}` });
  assert.deepEqual(droppedPaths(r), ["o/a.go"]);
});

test("--keep-generated counts a file with a wide marker", async () => {
  const r = await run({ "g/a.txt": `# generated file\n${lines("x", 6)}` }, ["--keep-generated"]);
  assert.equal(r.dropped.files, 0);
});

test("a compiled output beside its source is dropped and the line names the source", async () => {
  const r = await run({
    "lib/app.tl": lines("t", 6), "lib/app.lua": lines("l", 6),
    "web/site.scss": lines("s", 6), "web/site.css": lines("c", 6),
    "web/page.ts": lines("p", 6), "web/page.js": lines("j", 6),
  });
  assert.deepEqual(droppedPaths(r), ["lib/app.lua", "web/page.js", "web/site.css"]);
  assert.equal(r.dropped.classes.generated.files, 3);
  assert.match(droppedLine(r) ?? "", /compiled output of lib\/app\.tl/);
});

test("a compiled output under a directory that mirrors src is dropped", async () => {
  const r = await run({
    "src/core.coffee": lines("c", 6), "dist/core.js": lines("d", 6),
    "src/deep/view.tsx": lines("v", 6), "build/deep/view.js": lines("w", 6),
    "lib/styles/main.less": lines("m", 6), "src/styles/main.css": lines("n", 6),
  });
  // The last one is the wrong way round (the output is in src and the source is elsewhere), so it stays.
  assert.deepEqual(droppedPaths(r), ["build/deep/view.js", "dist/core.js"]);
});

test("a .js with only a .d.ts beside it, or with no source at all, is kept", async () => {
  const r = await run({
    "api/index.js": lines("i", 6), "api/index.d.ts": lines("t", 6),
    "solo/main.js": `const generated = require("x");\n${lines("m", 6)}`,
    "other/thing.c": lines("c", 6),
    "data/x.js": lines("d", 6), "data/x.json": lines("e", 6),
  });
  assert.equal(r.dropped.files, 0);
});

test("--keep-generated counts a compiled output", async () => {
  const r = await run({ "a/x.ts": lines("t", 6), "a/x.js": lines("j", 6) }, ["--keep-generated"]);
  assert.equal(r.dropped.files, 0);
});

test("a .gitattributes unset of linguist-generated keeps a compiled output", async () => {
  const r = await run({ ".gitattributes": "a/x.js -linguist-generated\n", "a/x.ts": lines("t", 6), "a/x.js": lines("j", 6) });
  assert.equal(r.dropped.files, 0);
});
